CREATE TABLE IF NOT EXISTS empleado_cambios (
  id INT AUTO_INCREMENT PRIMARY KEY,
  empresa_id INT NOT NULL,
  id_empleado INT NOT NULL,
  campo VARCHAR(60) NOT NULL,
  valor_anterior VARCHAR(255) NULL,
  valor_nuevo VARCHAR(255) NULL,
  registrado_por VARCHAR(80) NULL,
  creado_at DATETIME NOT NULL,
  INDEX idx_emp_cambios_emp (empresa_id, id_empleado),
  CONSTRAINT fk_emp_cambios_empresa FOREIGN KEY (empresa_id) REFERENCES empresas(id),
  CONSTRAINT fk_emp_cambios_empleado FOREIGN KEY (id_empleado) REFERENCES empleados(id) ON DELETE CASCADE
);
